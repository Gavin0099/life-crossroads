import Foundation

public enum Influence: String, Codable, Sendable {
    case playerChoice, family, socialEnvironment, otherPeople, randomness, modelRule
}

public struct Cost: Codable, Equatable, Sendable {
    public var time: Int
    public var energy: Int
    public var materials: Int
    public init(time: Int = 0, energy: Int = 0, materials: Int = 0) {
        self.time = time; self.energy = energy; self.materials = materials
    }
    public static func + (lhs: Self, rhs: Self) -> Self {
        .init(time: lhs.time + rhs.time, energy: lhs.energy + rhs.energy, materials: lhs.materials + rhs.materials)
    }
}

public struct CostStep: Codable, Equatable, Sendable {
    public let ruleID: String
    public let influence: Influence
    public let inputs: [String: Double]
    public let adjustment: Cost
    public let sourceIDs: [String]
    public let assumptionIDs: [String]
    public let explanation: String
}

public struct EffectStep: Codable, Equatable, Sendable {
    public let ruleID: String
    public let influence: Influence
    public let delta: ResourceValues
    public let assumptionIDs: [String]
    public let explanation: String
}

public struct RandomTrial: Codable, Equatable, Sendable {
    public let algorithm: String
    public let key: String
    public let draw: Double
    public let threshold: Double
    public let occurred: Bool
    public let assumptionID: String
}

public struct ConsequenceTrace: Codable, Equatable, Sendable {
    public let engineVersion: String
    public let dataVersion: String
    public let contentVersion: String
    public let seed: UInt64
    public let eventID: String
    public let choiceID: String
    public let age: Int
    public let countryCode: String
    public let householdID: String
    public let control: DecisionControl
    public let applied: Bool
    public let unavailableReasons: [String]
    public let observations: [IndicatorObservation]
    public let baseCost: Cost
    public let costSteps: [CostStep]
    public let finalCost: Cost
    public let budgetBefore: Cost
    public let budgetAfter: Cost
    public let effectSteps: [EffectStep]
    public let randomTrial: RandomTrial?
    public let resourcesBefore: ResourceValues
    public let resourcesAfter: ResourceValues
    public let scheduledHooks: [StoryHook]

    /// Text is assembled from executed rules, never generated by a language model.
    public var explanation: [String] {
        let quotes = costSteps.map(\.explanation)
        return applied ? quotes + effectSteps.map(\.explanation) : quotes + unavailableReasons
    }
}

public struct DecisionResult: Codable, Equatable, Sendable {
    public let state: LifeState
    public let trace: ConsequenceTrace
}
